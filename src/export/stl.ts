import type { ExportStl, MeshData } from '@/core/contracts';

const HEADER_BYTES = 80;
const COUNT_BYTES = 4;
const TRIANGLE_BYTES = 50;
const HEADER_LABEL = 'Binary STL generated by Text-to-CAD (units: mm)';

const at = (arr: ArrayLike<number>, index: number): number => arr[index] ?? 0;

/**
 * Codifica um `MeshData` no formato STL binário (little-endian, unidade mm).
 * Lança erro descritivo em PT-BR caso a malha esteja vazia ou inconsistente.
 */
export function encodeBinaryStl(mesh: MeshData): ArrayBuffer {
  const { positions, indices, triangleCount } = mesh;

  if (!Number.isInteger(triangleCount) || triangleCount <= 0) {
    throw new Error('Não é possível exportar STL de uma malha vazia ou inválida.');
  }

  if (indices.length < triangleCount * 3) {
    throw new Error('Índices de triângulos insuficientes para exportar o STL.');
  }

  const buffer = new ArrayBuffer(HEADER_BYTES + COUNT_BYTES + triangleCount * TRIANGLE_BYTES);
  const headerView = new Uint8Array(buffer, 0, HEADER_BYTES);
  for (let i = 0; i < HEADER_LABEL.length && i < HEADER_BYTES; i++) {
    headerView[i] = HEADER_LABEL.charCodeAt(i);
  }

  const view = new DataView(buffer);
  view.setUint32(HEADER_BYTES, triangleCount, true);

  for (let t = 0; t < triangleCount; t++) {
    const i0 = at(indices, t * 3) * 3;
    const i1 = at(indices, t * 3 + 1) * 3;
    const i2 = at(indices, t * 3 + 2) * 3;

    if (i0 + 2 >= positions.length || i1 + 2 >= positions.length || i2 + 2 >= positions.length) {
      throw new Error('Índice de vértice fora dos limites ao exportar STL.');
    }

    const x0 = at(positions, i0);
    const y0 = at(positions, i0 + 1);
    const z0 = at(positions, i0 + 2);

    const x1 = at(positions, i1);
    const y1 = at(positions, i1 + 1);
    const z1 = at(positions, i1 + 2);

    const x2 = at(positions, i2);
    const y2 = at(positions, i2 + 1);
    const z2 = at(positions, i2 + 2);

    const ux = x1 - x0;
    const uy = y1 - y0;
    const uz = z1 - z0;

    const vx = x2 - x0;
    const vy = y2 - y0;
    const vz = z2 - z0;

    const nx = uy * vz - uz * vy;
    const ny = uz * vx - ux * vz;
    const nz = ux * vy - uy * vx;
    const len = Math.hypot(nx, ny, nz);
    const validNormal = len > 1e-12 && Number.isFinite(len);

    const base = HEADER_BYTES + COUNT_BYTES + t * TRIANGLE_BYTES;
    view.setFloat32(base, validNormal ? nx / len : 0, true);
    view.setFloat32(base + 4, validNormal ? ny / len : 0, true);
    view.setFloat32(base + 8, validNormal ? nz / len : 1, true);

    view.setFloat32(base + 12, x0, true);
    view.setFloat32(base + 16, y0, true);
    view.setFloat32(base + 20, z0, true);

    view.setFloat32(base + 24, x1, true);
    view.setFloat32(base + 28, y1, true);
    view.setFloat32(base + 32, z1, true);

    view.setFloat32(base + 36, x2, true);
    view.setFloat32(base + 40, y2, true);
    view.setFloat32(base + 44, z2, true);

    view.setUint16(base + 48, 0, true);
  }

  return buffer;
}

/** Exporta uma malha avaliada como `Blob` STL binário (`model/stl`). */
export const exportStl: ExportStl = (mesh) =>
  new Blob([encodeBinaryStl(mesh)], { type: 'model/stl' });
